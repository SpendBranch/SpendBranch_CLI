#!/bin/sh
# Prints the Homebrew formula of a release: formula.sh <version> <SHA256SUMS>
# The release job writes it to Formula/spendbranch.rb in SpendBranch/homebrew-tap, so that
# `brew install spendbranch/tap/spendbranch` installs the archives the release published.
set -eu

version=$1 sums=$2
printf '%s' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$' || {
  echo "formula.sh: not a release version: $version" >&2
  exit 1
}
url="https://github.com/SpendBranch/SpendBranch_CLI/releases/download/v$version"

sum() {
  file="spendbranch-$version-$1.tar.gz"
  found=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1; exit }' "$sums")
  printf '%s' "$found" | grep -Eq '^[0-9a-f]{64}$' || {
    echo "formula.sh: $sums has no SHA-256 for $file" >&2
    exit 1
  }
  printf '%s' "$found"
}

# Each sum is taken first, so a missing one stops before anything is printed.
macos_arm=$(sum macos-arm64)
macos_x64=$(sum macos-x64)
linux_arm=$(sum linux-arm64)
linux_x64=$(sum linux-x64)

cat << EOF
# Generated by packaging/homebrew/formula.sh in SpendBranch/SpendBranch_CLI for v$version.
# Do not edit: the next release replaces it.
class Spendbranch < Formula
  desc "Collects only authorized AI coding agent session metadata for SpendBranch"
  homepage "https://github.com/SpendBranch/SpendBranch_CLI"
  version "$version"
  license :cannot_represent

  on_macos do
    on_arm do
      url "$url/spendbranch-$version-macos-arm64.tar.gz"
      sha256 "$macos_arm"
    end
    on_intel do
      url "$url/spendbranch-$version-macos-x64.tar.gz"
      sha256 "$macos_x64"
    end
  end

  on_linux do
    on_arm do
      url "$url/spendbranch-$version-linux-arm64.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$url/spendbranch-$version-linux-x64.tar.gz"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install "spendbranch"
  end

  def caveats
    <<~TEXT
      Connect this device:
        spendbranch setup

      Before uninstalling, disconnect and remove the agent hooks:
        spendbranch logout
        spendbranch hooks uninstall claude-code
        spendbranch hooks uninstall codex
    TEXT
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/spendbranch --version")
  end
end
EOF
